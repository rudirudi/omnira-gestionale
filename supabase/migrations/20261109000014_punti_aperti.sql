-- Punti aperti e discussioni: qualcuno apre un punto, gli altri rispondono (commenti),
-- un responsabile lo porta avanti e alla fine si segna come risolto (con l'esito).

create table public.discussions (
  id uuid primary key default gen_random_uuid(),
  number integer generated by default as identity unique,
  kind text not null default 'punto' check (kind in ('punto', 'discussione')),
  title text not null check (char_length(btrim(title)) between 3 and 200),
  body text check (body is null or char_length(body) <= 10000),
  status text not null default 'aperto' check (status in ('aperto', 'risolto')),
  priority text not null default 'normale' check (priority in ('bassa', 'normale', 'alta')),
  owner_id uuid references public.profiles (id) on delete set null,
  due_date date,
  project_id uuid references public.projects (id) on delete set null,
  client_id uuid references public.clients (id) on delete set null,
  resolution text check (resolution is null or char_length(resolution) <= 4000),
  resolved_at timestamptz,
  resolved_by uuid references public.profiles (id) on delete set null,
  created_by uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  replies_count integer not null default 0,
  last_activity_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz
);
create index discussions_open_idx on public.discussions (status, last_activity_at desc) where deleted_at is null;
create index discussions_project_idx on public.discussions (project_id) where deleted_at is null;
create index discussions_owner_idx on public.discussions (owner_id) where deleted_at is null;

alter table public.discussions enable row level security;
create policy discussions_select on public.discussions for select to authenticated
  using ((select public.is_staff()) and deleted_at is null);
create policy discussions_insert on public.discussions for insert to authenticated
  with check ((select public.is_staff()) and created_by = (select auth.uid()));
create policy discussions_update on public.discussions for update to authenticated
  using ((select public.is_staff()) and deleted_at is null)
  with check ((select public.is_staff()));
grant select, insert, update on public.discussions to authenticated;

-- Stato e date gestiti dal database; eliminare (logicamente) solo chi l'ha aperto o un amministratore
create or replace function public.discussions_before_write()
returns trigger language plpgsql set search_path = public as $$
begin
  if tg_op = 'UPDATE' then
    if new.created_by <> old.created_by or new.number <> old.number then
      raise exception 'Campo non modificabile';
    end if;
    if new.deleted_at is not null and old.deleted_at is null
       and old.created_by <> auth.uid() and not public.has_role(array['admin']::public.app_role[]) then
      raise exception 'Solo chi ha aperto il punto o un amministratore può eliminarlo';
    end if;
    new.updated_at := now();
  end if;
  if new.status = 'risolto' and (tg_op = 'INSERT' or old.status <> 'risolto') then
    new.resolved_at := now();
    new.resolved_by := auth.uid();
  elsif new.status = 'aperto' then
    new.resolved_at := null;
    new.resolved_by := null;
  end if;
  return new;
end $$;
create trigger discussions_before_write before insert or update on public.discussions
  for each row execute function public.discussions_before_write();

create trigger discussions_audit after insert or update or delete on public.discussions
  for each row execute function public.audit_row();

-- Avvisi: nuovo punto (a tutto il team), nuovo responsabile, risolto/riaperto (a chi partecipa)
create or replace function public.discussions_notify()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  actor uuid := coalesce(auth.uid(), new.created_by);
  actor_name text;
  what text := case when new.kind = 'punto' then 'un punto aperto' else 'una discussione' end;
  link_to text := '/discussioni/' || new.id;
  label text := '#' || new.number || ' · ' || new.title;
begin
  select full_name into actor_name from public.profiles where id = actor;
  if tg_op = 'INSERT' then
    insert into public.notifications (user_id, type, title, body, link, actor_id)
    select p.id, 'discussione',
           case when p.id = new.owner_id then actor_name || ' ti ha assegnato ' || what
                else actor_name || ' ha aperto ' || case when new.kind = 'punto' then 'un nuovo punto' else 'una nuova discussione' end end,
           label, link_to, actor
    from public.profiles p where p.active and p.id <> actor;
    return new;
  end if;

  if new.deleted_at is not null then return new; end if;

  if new.owner_id is distinct from old.owner_id and new.owner_id is not null and new.owner_id <> actor then
    insert into public.notifications (user_id, type, title, body, link, actor_id)
    values (new.owner_id, 'discussione', actor_name || ' ti ha assegnato ' || what, label, link_to, actor);
  end if;

  if new.status <> old.status then
    insert into public.notifications (user_id, type, title, body, link, actor_id)
    select distinct u, 'discussione',
           case when new.status = 'risolto' then actor_name || ' ha segnato come risolto' else actor_name || ' ha riaperto' end,
           label || case when new.status = 'risolto' and new.resolution is not null then ' — ' || left(new.resolution, 120) else '' end,
           link_to, actor
    from (
      select new.created_by as u
      union select new.owner_id
      union select c.author_id from public.comments c where c.entity_type = 'discussion' and c.entity_id = new.id
    ) r
    where u is not null and u <> actor and exists (select 1 from public.profiles where id = u and active);
  end if;
  return new;
end $$;
create trigger discussions_notify after insert or update on public.discussions
  for each row execute function public.discussions_notify();

-- Le risposte sono commenti (con @menzioni) sull'entità "discussion"
alter table public.comments drop constraint comments_entity_type_check;
alter table public.comments add constraint comments_entity_type_check
  check (entity_type in ('task', 'project', 'client', 'lead', 'discussion'));

create or replace function public.discussions_count_replies()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' and new.entity_type = 'discussion' then
    update public.discussions set replies_count = replies_count + 1, last_activity_at = new.created_at where id = new.entity_id;
  elsif tg_op = 'DELETE' and old.entity_type = 'discussion' then
    update public.discussions set replies_count = greatest(replies_count - 1, 0) where id = old.entity_id;
  end if;
  return null;
end $$;
create trigger comments_discussion_count after insert or delete on public.comments
  for each row execute function public.discussions_count_replies();

-- Avvisi sui commenti: aggiunte le discussioni (avvisati chi l'ha aperta, il responsabile e chi ha già risposto)
create or replace function public.notify_comment()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  t record;
  author_name text;
  link_to text;
  label text;
begin
  select full_name into author_name from public.profiles where id = new.author_id;
  if new.entity_type = 'task' then
    select tk.title, tk.number, p.code into t from public.tasks tk join public.projects p on p.id = tk.project_id where tk.id = new.entity_id;
    link_to := '/task?aperto=' || new.entity_id;
    label := t.code || '-' || t.number || ' · ' || t.title;
  elsif new.entity_type = 'project' then
    select name into label from public.projects where id = new.entity_id;
    link_to := '/progetti/' || new.entity_id || '?scheda=discussione';
  elsif new.entity_type = 'client' then
    select name into label from public.clients where id = new.entity_id;
    link_to := '/clienti/' || new.entity_id;
  elsif new.entity_type = 'discussion' then
    select '#' || number || ' · ' || title into label from public.discussions where id = new.entity_id;
    link_to := '/discussioni/' || new.entity_id;
  else
    select title into label from public.leads where id = new.entity_id;
    link_to := '/lead?aperto=' || new.entity_id;
  end if;

  insert into public.notifications (user_id, type, title, body, link, actor_id)
  select distinct u, case when u = any (new.mentions) then 'menzione' else 'commento' end,
         case when u = any (new.mentions) then author_name || ' ti ha menzionato'
              when new.entity_type = 'discussion' then author_name || ' ha risposto'
              else author_name || ' ha commentato' end,
         coalesce(label, '') || ': ' || left(new.body, 140), link_to, new.author_id
  from (
    select unnest(new.mentions) as u
    union
    select ta.user_id from public.task_assignees ta where new.entity_type = 'task' and ta.task_id = new.entity_id
    union
    select d.created_by from public.discussions d where new.entity_type = 'discussion' and d.id = new.entity_id
    union
    select d.owner_id from public.discussions d where new.entity_type = 'discussion' and d.id = new.entity_id
    union
    select c.author_id from public.comments c where new.entity_type = 'discussion' and c.entity_type = 'discussion' and c.entity_id = new.entity_id
  ) r
  where u is not null and u <> new.author_id and exists (select 1 from public.profiles where id = u and active);
  return new;
end $$;

revoke execute on function public.discussions_before_write(), public.discussions_notify(), public.discussions_count_replies(), public.notify_comment()
  from public, anon, authenticated;
